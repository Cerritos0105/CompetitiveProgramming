#include <bits/stdc++.h>
using namespace std;
typedef long long ll;

void solve() {
    int x; cin >> x;
    int n; cin >> n;
    vector<ll> v(n);
    for(int i =0; i < n; i++){
        cin >> v[i];
    }
    sort(v.begin(), v. end());
    vector<ll> dp(x+1, x+1);
    dp[0]=0;
    for(int i =1; i <= x; i ++){
        for(int j=0;j < n; j++){
            if(i>=v[j]){
                dp[i]= min(dp[i], dp[i-v[j]]+1);
            }
        }
    }
    cout<<dp[x]<<"\n";
}

int main() {
    int t=1;
    //cin >> t;
    while(t--){
        solve();
    }  
    return 0;
 }