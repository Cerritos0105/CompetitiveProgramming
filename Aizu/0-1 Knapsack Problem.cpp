#include <algorithm>
#include <bits/stdc++.h>

using namespace std;
typedef long long ll;

void solve() {
    int n, W; cin >>n >>W;
    vector<int> v(n);
    vector<int> w(n);
    for(int i =0; i <n; i++){
        cin >> v[i] >> w[i];
    }
    vector<ll> dp(W+1,0);
    for(int i =0; i <n; i++){
        int v1=v[i], w1 = w[i];
        for(int j = W; j  >= w1; j--){
            dp[j]= max(dp[j], v1+dp[j-w1]);
        }
    }
    cout<<dp[W]<<"\n";
}

int main() {//ios::sync_with_stdio(false);cin.tie(nullptr);
    int t=1;
    //cin >> t;
    while(t--){
        solve();
    }  
    return 0;
 }