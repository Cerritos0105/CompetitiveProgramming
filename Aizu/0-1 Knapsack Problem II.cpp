#include <algorithm>
#include <bits/stdc++.h>
using namespace std;
typedef long long ll;
void solve() {
    int n, W; cin >>n >>W;
    vector<ll> v(n);
    vector<ll> w(n);
    ll mv=0;
    for(int i =0; i <n; i++){
        cin >> v[i] >> w[i];
        mv+=v[i];
    }
    ll INF = LLONG_MAX / 2;
    vector<long long> dp(mv + 1, INF);
    dp[0]=0;
    for (int i = 0; i < n; i++){
        for (int j = mv; j >= (int)v[i]; j--){
            if (dp[j - v[i]] + w[i] < dp[j]){
                dp[j] = dp[j - v[i]] + w[i];
            }
        }
    }
    int ans = 0;
    for (int j = 0; j <= mv; j++){
        if (dp[j] <= W) ans = j;
    }

    cout << ans << endl;
    
}

int main() {ios::sync_with_stdio(false);cin.tie(nullptr);
    int t=1;
    //cin >> t;
    while(t--){
        solve();
    }  
    return 0;
 }